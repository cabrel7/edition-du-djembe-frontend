<script>
import { Target, Eye, Heart, Users, Award, BookOpen, Globe, Mail, Building2, ChevronDown } from 'lucide-vue-next'
import { mapState, mapActions } from 'vuex'

export default {
  name: 'AboutPage',

  components: {
    Target,
    Eye,
    Heart,
    Users,
    Award,
    BookOpen,
    Globe,
    Mail,
    Building2,
    ChevronDown
  },

  data() {
    return {
      // Valeurs fondamentales
      coreValues: [
        {
          icon: 'Award',
          title: "Excellence",
          description: "Nous visons la plus haute qualité dans chacune de nos publications.",
        },
        {
          icon: 'Users',
          title: "Accompagnement",
          description: "Un suivi personnalisé pour chaque auteur, à chaque étape du projet.",
        },
        {
          icon: 'BookOpen',
          title: "Accessibilité",
          description: "Rendre le savoir accessible au plus grand nombre est notre priorité.",
        },
        {
          icon: 'Heart',
          title: "Passion",
          description: "L'amour des livres et de la transmission anime notre équipe.",
        },
      ],
      
      // Avatar par défaut
      defaultAvatar: 'https://images.unsplash.com/photo-1633332755192-727a05c4013d?w=200&h=200&fit=crop',
      
      // État pour les bios dépliables
      showBio: {},
      
      // États de chargement
      loading: false,
      loadingPartners: false,
      
      // Informations légales
      legalInfo: {
        company: "Éditions du Djembé d'Ébène",
        address: "12263 boulevard Saint Claude",
        city: "Québec, Canada",
        director: "Dr Nono Gaël Tanguy"
      }
    }
  },

  computed: {
    ...mapState({
      allTeamMembers: state => state.publicData.allTeamMembers,
      lastTeamMembers: state => state.publicData.lastTeamMembers,
      allPartners: state => state.publicData.allPartners,
      lastPartners: state => state.publicData.lastPartners
    }),
    
    // Membres filtrés (actifs et triés par ordre d'affichage)
    filteredTeamMembers() {
      if (!this.allTeamMembers || this.allTeamMembers.length === 0) {
        return this.lastTeamMembers || [];
      }
      
      return this.allTeamMembers
        .filter(member => member.is_active !== false) // Afficher seulement les actifs
        .sort((a, b) => {
          // Trier par ordre d'affichage, puis par date de création
          const orderA = a.display_order || 999;
          const orderB = b.display_order || 999;
          return orderA - orderB;
        });
    },
    
    // Partenaires actifs
    activePartners() {
      if (!this.allPartners || this.allPartners.length === 0) {
        return this.lastPartners || [];
      }
      
      return this.allPartners
        .filter(partner => partner.is_active !== false)
        .sort((a, b) => {
          const orderA = a.display_order || 999;
          const orderB = b.display_order || 999;
          return orderA - orderB;
        })
        .slice(0, 12); // Limiter à 12 partenaires max
    },
    
    // Trouver le fondateur (basé sur le rôle)
    founder() {
      const founders = this.filteredTeamMembers.filter(member => 
        member.role && member.role.toLowerCase().includes('fondateur') ||
        member.role && member.role.toLowerCase().includes('directeur') ||
        member.nom === 'Tanguy' || 
        member.prenom === 'Gaël' ||
        member.prenom === 'Nono'
      );
      
      return founders.length > 0 ? founders[0] : this.filteredTeamMembers[0];
    }
  },

  methods: {
    ...mapActions([
      'fetchPublicTeamMembers',
      'fetchPublicPartners'
    ]),
    
    // Basculer l'affichage de la bio
    toggleBio(memberId) {
      this.showBio[memberId] = !this.showBio[memberId];
    },
    
    // Charger les données de l'équipe
    async loadTeamData() {
      try {
        this.loading = true;
        // Si nous n'avons pas de données dans allTeamMembers, charger depuis l'API
        if (!this.allTeamMembers || this.allTeamMembers.length === 0) {
          await this.fetchPublicTeamMembers();
        }
      } catch (error) {
        console.error('Erreur lors du chargement de l\'équipe:', error);
      } finally {
        this.loading = false;
      }
    },
    
    // Charger les données des partenaires
    async loadPartnersData() {
      try {
        this.loadingPartners = true;
        // Si nous n'avons pas de données dans allPartners, charger depuis l'API
        if (!this.allPartners || this.allPartners.length === 0) {
          await this.fetchPublicPartners();
        }
      } catch (error) {
        console.error('Erreur lors du chargement des partenaires:', error);
      } finally {
        this.loadingPartners = false;
      }
    },
    
    // Format SIRET (si nécessaire)
    formatSiret(siret) {
      return siret?.replace(/(\d{3})(\d{3})(\d{3})(\d{5})/, '$1 $2 $3 $4') || '';
    }
  },

  async mounted() {
    console.log('About page mounted');
    
    // Charger les données si elles ne sont pas déjà présentes
    if (!this.allTeamMembers || this.allTeamMembers.length === 0) {
      await this.loadTeamData();
    }
    
    if (!this.allPartners || this.allPartners.length === 0) {
      await this.loadPartnersData();
    }
  }
}
